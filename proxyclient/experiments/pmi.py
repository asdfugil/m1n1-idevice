	u.msr(PMESR1_EL1, 0, call=call)
	u.msr(PMC0_EL1, 0, call=call)
	u.msr(PMC1_EL1, 0, call=call)
	u.msr(PMC2_EL1, 0, call=call)
	u.msr(PMC3_EL1, 0, call=call)
	u.msr(PMC4_EL1, 0, call=call)
	u.msr(PMC5_EL1, 0, call=call)
