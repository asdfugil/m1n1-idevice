def test_pmi(call):
	# Reset counters

	u.msr(PMCR0_EL1, 0, call=call)
	u.msr(PMCR1_EL1, 0, call=call)
	u.msr(PMC0_EL1, 0, call=call)

	# Enable counter 0 (Active Cycle)

	u.msr(PMCR0_EL1, imode | PMCR0_CNT_ENABLE_0 | PMCR0_PMI_ENABLE_0, call=call)
	u.msr(PMCR1_EL1, -1, call=call)

	# 1 second worth of cycles
	u.msr(PMC0_EL1, -1 * freq & 0x7fffffffffff, call=call) # 47 bit

	if cpu != 0:
		if imode == PMCR0_IMODE_FIQ:
			u.msr(DAIF, 2 << 6, call=call)
		elif imode == PMCR0_IMODE_AIC:
			u.msr(DAIF, 1 << 6, call=call)

	print("PMC interrupt below")
	call(util.spin_1sec)
	print("PMC interrupt above")

	if cpu != 0:
		u.msr(DAIF, 3 << 6, call=call)

	print("PMCR0_EL1:", hex(u.mrs(PMCR0_EL1, call=call)))
	print("PMCR1_EL1:", hex(u.mrs(PMCR1_EL1, call=call)))
	print("PMC0_EL1:", hex(u.mrs(PMC0_EL1, call=call)))
	print("PMSR_EL1:", hex(u.mrs(PMSR_EL1, call=call)))

	u.msr(PMCR0_EL1, 0, call=call)
	u.msr(PMCR1_EL1, 0,call=call)
	u.msr(PMC0_EL1, 0, call=call)
	u.inst(0xd5033fdf, call=call) # isb

